#!/usr/bin/env python3
"""Multi-agent adapter synchronizer for Demiurge Core.

Dynamically discovers all governance rules in `.agents/rules/*.md` and all skills
in `.agents/skills/*/SKILL.md` (parsing YAML frontmatter `name` and `description`),
then generates thin, non-duplicating bridge files pointing to `AGENTS.md` and
`.agents/` as the single source of truth:

- `CLAUDE.md` (Claude Code)
- `.cursor/rules/demiurge-core.mdc` (Cursor)
- `.github/copilot-instructions.md` (GitHub Copilot)

Use `--check` in CI or pre-commit hooks to verify all adapter files are in sync.
"""
from __future__ import annotations

import argparse
import difflib
import re
import sys
from pathlib import Path

import yaml

AUTO_HEADER = (
    "<!-- AUTO-GENERATED by scripts/sync_agent_adapters.py — DO NOT EDIT DIRECTLY. "
    "Edit AGENTS.md or .agents/ and re-run `python scripts/sync_agent_adapters.py`. -->"
)

FRONTMATTER_RE = re.compile(r"^---\r?\n(.*?)\r?\n---(?:\r?\n|$)", re.DOTALL)
H1_RE = re.compile(r"^#\s+(.+)$", re.MULTILINE)


def normalize_whitespace(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def escape_table_cell(text: str) -> str:
    return text.replace("|", "\\|")


def parse_frontmatter(content: str) -> tuple[dict[str, object], str]:
    match = FRONTMATTER_RE.match(content)
    if not match:
        return {}, content
    raw = yaml.safe_load(match.group(1))
    data = raw if isinstance(raw, dict) else {}
    return data, content[match.end() :]


def discover_rules(repo_root: Path) -> list[dict[str, str]]:
    rules_dir = repo_root / ".agents" / "rules"
    if not rules_dir.is_dir():
        return []

    rules: list[dict[str, str]] = []
    for rule_file in sorted(rules_dir.glob("*.md"), key=lambda p: p.name.lower()):
        content = rule_file.read_text(encoding="utf-8")
        fm, body = parse_frontmatter(content)

        title = str(fm.get("title") or fm.get("name") or "").strip()
        if not title:
            h1 = H1_RE.search(body)
            title = h1.group(1).strip() if h1 else rule_file.stem.replace("-", " ").title()
        title = normalize_whitespace(title.replace("`", ""))

        description = normalize_whitespace(str(fm.get("description") or ""))
        rel_path = rule_file.relative_to(repo_root).as_posix()
        rules.append(
            {
                "slug": rule_file.stem,
                "title": title,
                "description": description,
                "path": rel_path,
            }
        )
    return rules


def discover_skills(repo_root: Path) -> list[dict[str, str]]:
    skills_dir = repo_root / ".agents" / "skills"
    if not skills_dir.is_dir():
        return []

    skills: list[dict[str, str]] = []
    for skill_file in sorted(skills_dir.glob("*/SKILL.md"), key=lambda p: p.parent.name.lower()):
        content = skill_file.read_text(encoding="utf-8")
        fm, body = parse_frontmatter(content)

        name = normalize_whitespace(str(fm.get("name") or skill_file.parent.name))
        description = normalize_whitespace(str(fm.get("description") or ""))
        if not description:
            h1 = H1_RE.search(body)
            description = normalize_whitespace(h1.group(1)) if h1 else f"Skill definition for {name}."

        rel_path = skill_file.relative_to(repo_root).as_posix()
        skills.append(
            {
                "name": name,
                "description": description,
                "path": rel_path,
            }
        )
    return skills


def render_shared_body(rules: list[dict[str, str]], skills: list[dict[str, str]]) -> str:
    lines: list[str] = [
        "## Single Source of Truth",
        "",
        "Do **not** duplicate vault rules or skill procedures here. Always read these canonical files first:",
        "",
        "- **`AGENTS.md`** — Foundational vault conventions, YAML frontmatter standard, narrative authority, passive scores, and Atlas VTT `0.16.0` limits.",
        "- **`campaign.config.json`** — Active campaign name, vault folder (`vault_dir`), Atlas collection, grid units, party roster/passives, and roll table presets.",
        "- **`.agents/rules/`** — Mandatory governance rules (read the relevant rule before writing to the vault).",
        "- **`.agents/skills/`** — Modular DM workflows and Python CLI toolkits.",
        "",
        "## Non-Negotiable Guardrails (Summary Pointers)",
        "",
        "1. **DM-as-Reviewer:** Never invent canonical NPCs, factions, buildings, temples, or handout text without explicit DM approval (see `.agents/rules/dm-reviewer-narrative-authority.md`).",
        "2. **Session Startup Check:** Confirm whether any sessions were played since the last chat before planning or updating canon (see `.agents/rules/session-lifecycle.md`).",
        "3. **Atlas VTT `0.16.0` Technical Limits:** Keep every linked note, DM Dashboard, and statblock strictly under **32 KB** (target `< 30 KB`), never hand-edit `.atlas-data/assets-metadata.json`, and ensure the scene tab is closed in Obsidian before scripted `.atlasmap` edits (see `.agents/rules/vtt-sync-boundaries.md` and `.agents/rules/scene-and-dashboard-standards.md`).",
        "4. **Staging vs. Canon:** Log improvised table content only to `Campaign/Improv Log.md` after DM confirmation (see `.agents/rules/live-improv-and-boundaries.md`).",
        "5. **Never Commit Private Sources:** Keep `Sources/`, `Manuals/`, `Reference/`, and `Archive/` read-only and untracked.",
        "",
        "## Governance Rules (`.agents/rules/`)",
        "",
        "| Rule | File |",
        "| :--- | :--- |",
    ]

    for rule in rules:
        label = escape_table_cell(rule["title"])
        if rule["description"]:
            label = f"{label} — {escape_table_cell(rule['description'])}"
        lines.append(f"| {label} | `{rule['path']}` |")

    lines.extend(
        [
            "",
            "## Modular Skills (`.agents/skills/`)",
            "",
            "| Skill | Purpose | Definition |",
            "| :--- | :--- | :--- |",
        ]
    )

    for skill in skills:
        sname = escape_table_cell(skill["name"])
        sdesc = escape_table_cell(skill["description"])
        lines.append(f"| `{sname}` | {sdesc} | `{skill['path']}` |")

    lines.extend(
        [
            "",
            "## Verification Commands",
            "",
            "```bash",
            "# Validate YAML frontmatter, wikilinks, Atlas 32 KB limits, and full Atlas integrity",
            "python scripts/lint_vault.py --strict-links --full-atlas",
            "",
            "# Verify multi-agent adapter files remain synchronized with AGENTS.md & .agents/",
            "python scripts/sync_agent_adapters.py --check",
            "```",
        ]
    )

    return "\n".join(lines)


def build_adapters(repo_root: Path) -> dict[Path, str]:
    rules = discover_rules(repo_root)
    skills = discover_skills(repo_root)
    shared = render_shared_body(rules, skills)

    claude_content = "\n".join(
        [
            AUTO_HEADER,
            "",
            "# CLAUDE.md — Demiurge Core (Claude Code Bridge)",
            "",
            "This file adapts **Demiurge Core** for Claude Code. Treat `AGENTS.md`, `campaign.config.json`, and `.agents/` as the canonical instructions for every task.",
            "",
            shared,
            "",
        ]
    )

    cursor_content = "\n".join(
        [
            "---",
            'description: "Demiurge Core governance bridge pointing Cursor to AGENTS.md, campaign.config.json, and all .agents/ rules and skills."',
            "alwaysApply: true",
            "---",
            "",
            AUTO_HEADER,
            "",
            "# Demiurge Core — Cursor Governance Bridge",
            "",
            "This always-applied Cursor rule delegates all campaign, Obsidian, and Atlas VTT `0.16.0` behavior to `AGENTS.md`, `campaign.config.json`, and `.agents/`.",
            "",
            shared,
            "",
        ]
    )

    copilot_content = "\n".join(
        [
            AUTO_HEADER,
            "",
            "# GitHub Copilot Instructions — Demiurge Core",
            "",
            "This file configures GitHub Copilot for **Demiurge Core**. Treat `AGENTS.md`, `campaign.config.json`, and `.agents/` as the single source of truth for all rules, skills, and vault workflows.",
            "",
            shared,
            "",
        ]
    )

    return {
        repo_root / "CLAUDE.md": claude_content,
        repo_root / ".cursor" / "rules" / "demiurge-core.mdc": cursor_content,
        repo_root / ".github" / "copilot-instructions.md": copilot_content,
    }


def sync_adapters(repo_root: Path, check_only: bool = False) -> int:
    expected = build_adapters(repo_root)
    out_of_sync: list[tuple[Path, str, str | None]] = []

    for target_path, content in expected.items():
        if target_path.is_file():
            current = target_path.read_text(encoding="utf-8").replace("\r\n", "\n")
        else:
            current = None

        if check_only:
            if current != content:
                out_of_sync.append((target_path, content, current))
        else:
            target_path.parent.mkdir(parents=True, exist_ok=True)
            with target_path.open("w", encoding="utf-8", newline="\n") as fh:
                fh.write(content)
            rel = target_path.relative_to(repo_root).as_posix()
            status = "unchanged" if current == content else "updated"
            print(f"[{status}] {rel}")

    if check_only:
        if not out_of_sync:
            print(f"All {len(expected)} agent adapter files are up to date.")
            return 0

        print("ERROR: Agent adapter files are out of sync with AGENTS.md / .agents/:", file=sys.stderr)
        for target_path, expected_text, current_text in out_of_sync:
            rel = target_path.relative_to(repo_root).as_posix()
            if current_text is None:
                print(f"\n--- MISSING: {rel}", file=sys.stderr)
                continue
            diff = difflib.unified_diff(
                current_text.splitlines(keepends=True),
                expected_text.splitlines(keepends=True),
                fromfile=f"{rel} (on disk)",
                tofile=f"{rel} (expected)",
                n=2,
            )
            sys.stderr.writelines(diff)
        print(
            "\nRun `python scripts/sync_agent_adapters.py` to regenerate adapter files.",
            file=sys.stderr,
        )
        return 1

    return 0


def main(argv: list[str] | None = None) -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    if hasattr(sys.stderr, "reconfigure"):
        sys.stderr.reconfigure(encoding="utf-8", errors="replace")

    default_root = Path(__file__).resolve().parent.parent
    parser = argparse.ArgumentParser(
        description="Generate or verify multi-agent bridge files from AGENTS.md and .agents/."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify generated adapters match disk without writing (exits 1 if out of sync).",
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=default_root,
        help="Repository root directory (defaults to the Demiurge Core repo root).",
    )
    args = parser.parse_args(argv)
    return sync_adapters(args.root.resolve(), check_only=args.check)


if __name__ == "__main__":
    raise SystemExit(main())
